// A directive comment is a comment that a compiler or a tool reads, or may
// read. Its leaves keep tokenFlagComment and add tokenFlagDirective, so a
// consumer that skips comments can still treat a changed directive as a token
// change. Two layers decide it, and over-flagging is the safe direction:
//
//  1. directiveMarkers: known directives per language, matched anywhere in the
//     comment's text: a best-effort list, not complete.
//  2. commentLooksLikeProse: any other comment is a directive unless its body
//     has the shape of plain prose.
//
// docs/snapshot-format.md states both; TestDirectiveComments pins them.

// directiveDocMarkers are, per language, the comment openings that make a
// comment documentation read by a tool, and so always a directive: Rust's
// doc comments, which rustdoc compiles as tests, and C#'s XML doc comments,
// which the compiler reads under -doc / GenerateDocumentationFile (warnings
// CS1570 to CS1591, <include> and <inheritdoc>). A marker followed by the
// same character again (//// or /***) is an ordinary comment.
var directiveDocMarkers = map[string][]string{
	"Rust": {"///", "//!", "/**", "/*!"},
	"C#":   {"///"},
}

// proseDocMarkers are the documentation openings after which plain prose is
// still prose (JSDoc, Javadoc, Doxygen): the shape rule reads the body after
// them.
var proseDocMarkers = map[string][]string{
	"C":          {"///", "//!", "/**", "/*!"},
	"C#":         {"/**"},
	"Java":       {"/**"},
	"JavaScript": {"/**"},
	"TypeScript": {"/**"},
}

