// cLineCommentContinues matches a line of a comment that ends in a backslash
// followed only by spaces or tabs.
var cLineCommentContinues = regexp.MustCompile(`(?m)\\[ \t]*$`)

// fallThroughComment matches the fall-through comments compilers and linters
// read (GCC's -Wimplicit-fallthrough, ESLint's no-fallthrough, javac -Xlint),
// in any case: fallthrough, fall through, falls through, fall-thru, fall thru.
var fallThroughComment = regexp.MustCompile(`(?i)fall(s|ing)?[ \t-]*thr(u|ough)`)

// directivePatterns are known directives a substring cannot state.
var directivePatterns = map[string][]*regexp.Regexp{
	"Python": {
		regexp.MustCompile(`coding[:=]`),     // PEP 263 encoding declaration
		regexp.MustCompile(`(?i)\bpragma\b`), // coverage.py pragmas, with or without the colon
	},
	"Go": {
		// go/ast.IsGenerated: a line comment "// Code generated ... DO NOT EDIT."
		regexp.MustCompile(`^// Code generated .* DO NOT EDIT\.$`),
		// analysistest expectations.
		regexp.MustCompile(`^//\s*want\s`),
	},
	// A trigraph: ??/ is a backslash in ISO modes, so a line comment ending
	// in one swallows the next line.
	"C": {fallThroughComment, regexp.MustCompile(`\?\?[=/'()!<>-]`)},
	// javac translates Unicode escapes before it reads comments, so
	// `\u000a` in a comment ends it and the rest of the line is code.
	"Java":       {fallThroughComment, regexp.MustCompile(`\\u+[0-9A-Fa-f]{4}`)},
	"JavaScript": {fallThroughComment},
	"TypeScript": {fallThroughComment},
}

// commonDirectiveMarkers are tool markers that apply in every declared
// language: JetBrains inspections, SonarQube, and generated-code banners.
var commonDirectiveMarkers = []string{"noinspection", "NOSONAR", "DO NOT EDIT", "@generated"}

// directiveComment reports whether one comment, given as its whole text, is a
// directive in the language.
func directiveComment(language, text string) bool {
	for _, marker := range directiveDocMarkers[language] {
		if strings.HasPrefix(text, marker) && !strings.HasPrefix(text[len(marker):], marker[len(marker)-1:]) {
			return true
		}
	}
	for _, marker := range directiveMarkers[language] {
		if strings.Contains(text, marker) {
			return true
		}
	}
	for _, marker := range commonDirectiveMarkers {
		if strings.Contains(text, marker) {
			return true
		}
	}
	for _, pattern := range directivePatterns[language] {
		if pattern.MatchString(text) {
			return true
		}
	}
	if commentHoldsHiddenBreakOrSpace(text) {
		return true
	}
	// C: a line comment whose line ends in a backslash, even one followed by
	// spaces or tabs, continues onto the next line for GCC and clang, while
	// tree-sitter-c ends the comment there.
	if language == "C" && strings.HasPrefix(text, "//") && cLineCommentContinues.MatchString(text) {
		return true
	}
	// Ruby: an embedded document (=begin … =end) must start and end in column
	// 0; the grammar takes an indented =begin or =end as a comment all the
	// same, so its position and text must be compared.
	if language == "Ruby" && strings.HasPrefix(text, "=begin") {
		return true
	}
	return !commentLooksLikeProse(language, text)
}

// commentHoldsHiddenBreakOrSpace reports whether a comment holds anything
// other than printable text and plain layout. Defined positively: the text
// must be valid UTF-8, and every character a letter, mark, number,
// punctuation or symbol (Unicode categories L, M, N, P, S), U+0020, tab, line
// feed or carriage return. Everything else is flagged: an invalid byte
// sequence (Go, Python and Rust reject the file), a control character, a
// format character (the bidirectional controls, which Rust rejects by
// default, zero-width characters, U+FEFF), a separator other than the plain
// space (U+2028 and U+2029, where tsc ends a line; C# also ends one at the
// control U+0085), a private-use or unassigned code point.
func commentHoldsHiddenBreakOrSpace(text string) bool {
	for i := 0; i < len(text); {
		r, size := utf8.DecodeRuneInString(text[i:])
		i += size
		if r == utf8.RuneError && size <= 1 {
			return true
		}
		if r == ' ' || r == '\t' || r == '\n' || r == '\r' {
			continue
		}
		if !unicode.In(r, unicode.L, unicode.M, unicode.N, unicode.P, unicode.S) {
			return true
		}
	}
	return false
}

// commentLooksLikeProse is the shape rule. After the comment marker (or a
// documentation marker the language defines) comes at least one space or tab;
// then every non-empty line of the body (a block comment's lines with any
// leading `*` removed) must start with a word made only of letters (an
// apostrophe inside it allowed), optionally ended by one or more of . , ; ? ! )
// and followed by a space or the end of the line. Anything else is not prose:
// a body that is a single word, a body that begins with @ # ! + - < [ { $ or a
// digit, a word joined to `:`, `=`, `-`, `_`, `(` or a digit, an empty comment.
func commentLooksLikeProse(language, text string) bool {
	var body string
	switch {
	case strings.HasPrefix(text, "//"):
		body = text[2:]
		body = stripProseDocMarker(language, "//", body)
	case strings.HasPrefix(text, "/*"):
		body = strings.TrimSuffix(text[2:], "*/")
		body = stripProseDocMarker(language, "/*", body)
	case strings.HasPrefix(text, "=begin"): // Ruby block comment
		body = strings.TrimSuffix(strings.TrimSuffix(strings.TrimPrefix(text, "=begin"), "\n"), "=end")
	case strings.HasPrefix(text, "#"):
		body = text[1:]
	default:
		return false
	}
	if body == "" || !(body[0] == ' ' || body[0] == '\t' || body[0] == '\n' || body[0] == '\r') {
		return false
	}
	lines, words := 0, 0
	for _, line := range strings.Split(body, "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(text, "/*") {
			line = strings.TrimSpace(strings.TrimLeft(line, "*"))
		}
		if line == "" {
			continue
		}
		lines++
		words += len(strings.Fields(line))
		if !proseLine(line) {
			return false
		}
	}
	// A body of a single bare word is no prose, whatever the word: tool
	// markers are often one word (nosec, nocov, skipcq) and no list of them
	// can be complete.
	return lines > 0 && words > 1
}

func stripProseDocMarker(language, opening, body string) string {
	for _, marker := range proseDocMarkers[language] {
		if strings.HasPrefix(marker, opening) {
			rest := marker[len(opening):]
			if strings.HasPrefix(body, rest) && !strings.HasPrefix(body[len(rest):], rest) {
				return body[len(rest):]
			}
		}
	}
	return body
}

func proseLine(line string) bool {
	word := line
	if i := strings.IndexFunc(line, unicode.IsSpace); i >= 0 {
		word = line[:i]
	}
	word = strings.TrimRight(word, ".,;?!)")
	if word == "" {
		return false
	}
	runes := []rune(word)
	for i, r := range runes {
		if unicode.IsLetter(r) {
			continue
		}
		if (r == '\'' || r == '’') && i > 0 && i < len(runes)-1 {
			continue
		}
		return false
	}
	return true
}

